import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(process.env.PLAYWRIGHT_MODULES+'/');
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.clock.install({time:new Date('2026-10-06T07:00:00Z')});
await page.goto('http://127.0.0.1:5174/');
await page.getByRole('heading',{name:/What.s your name/}).waitFor();
await page.getByLabel('Your name').fill('Test Builder');
await page.getByRole('button',{name:'Next',exact:true}).click();
await page.getByLabel('Email address').fill('Test@Example.com');
await page.getByRole('button',{name:'Next',exact:true}).click();
await page.getByRole('button',{name:'Start today'}).click();
await page.getByRole('button',{name:'Next',exact:true}).click();
await page.getByRole('button',{name:/Start my 90 days/}).click();
await page.getByRole('heading',{name:'Set up your profiles.'}).waitFor();
assert.equal(JSON.parse(await page.evaluate(()=>localStorage.getItem('buildup-posting-profile-v1'))).start,'2026-10-06');
assert.equal(await page.locator('[data-date="2026-10-06"].setup').count(),1);
assert.equal(await page.locator('[data-date="2026-10-06"] button').count(),0);
assert.equal(await page.locator('[data-date="2026-10-08"] .content-type').innerText(),'Reel');
assert.equal(await page.getByText('/ 55 posts completed').count(),1);
assert.equal(await page.getByRole('button',{name:'Yes, posted',exact:true}).count(),0);
await page.getByRole('button',{name:'Edit schedule',exact:true}).click();
assert.equal(await page.getByLabel('Schedule for October 6',{exact:true}).isDisabled(),true);
await page.getByRole('button',{name:'Cancel',exact:true}).click();
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'outputs/setup-mobile.png',fullPage:true});
await context.close();
const nextContext=await browser.newContext();
const next=await nextContext.newPage();
next.on('pageerror',e=>errors.push(e.message));
await next.clock.install({time:new Date('2026-10-09T07:00:00Z')});
await next.addInitScript(()=>localStorage.setItem('buildup-posting-profile-v1',JSON.stringify({id:'test-id',name:'Test Builder',email:'test@example.com',note:'',start:'2026-10-06',synced:true})));
await next.goto('http://127.0.0.1:5174/');
await next.getByRole('button',{name:'Mark October 7 missed',exact:true}).click();
assert.equal(await next.getByRole('button',{name:'Mark October 8 posted',exact:true}).count(),1);
await next.getByRole('button',{name:'Mark October 8 posted',exact:true}).click();
await next.getByRole('button',{name:'Mark October 9 posted',exact:true}).waitFor();
assert.equal(await next.locator('.score-stat strong').innerText(),'0pts');
await next.reload();
assert.equal(await next.locator('[data-date="2026-10-07"].missed').count(),1);
assert.equal(await next.locator('[data-date="2026-10-08"].completed').count(),1);
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser checks passed: setup day, moved Reel, 55 posts, locks, persistence, score, and mobile layout.');
